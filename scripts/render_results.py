"""Render RESULTS.md from stored result files.

A row without a result file is not a row. Dates and commands come from the
files themselves, never from strings in the code. Run the pipeline
(`rcc ingest`, `rcc demo`, `rcc eval`, `scripts/load_test.py`) to write the
files, then:

    uv run python scripts/render_results.py --write

Cost: the served figure is generated from recorded per-call usage (task 4)
plus an infrastructure term; the OpenRouter activity-log figure for a
deployed window is a manual entry (see `results/openrouter_*.json`).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

RESULTS_DIR = Path("results")


def _latest(kind: str) -> dict[str, Any] | None:
    files = sorted(RESULTS_DIR.glob(f"{kind}_*.json"))
    if not files:
        return None
    data = json.loads(files[-1].read_text())
    data["_file"] = files[-1].name
    return data


def _row(metric: str, value: str, command: str, date: str) -> str:
    return f"| {metric} | {value} | `{command}` | {date[:10]} |"


def _pct(x: float) -> str:
    return f"{x * 100:.2f}%"


def render() -> str:
    lines: list[str] = ["# Results", ""]
    lines.append(
        "Each result: the number, the exact command that produced it, and the date. "
        "Generated by `scripts/render_results.py` from `results/*.json` — a row without "
        "a stored file is not a row."
    )
    lines.append("")

    ingest = _latest("ingest")
    demo = _latest("demo")
    ev = _latest("eval")
    load = _latest("load")

    lines += ["## Stage 0 — ingestion", "", "| Metric | Value | Command | Date |", "|---|---|---|---|"]
    if ingest:
        cmd, date = ingest["command"], ingest["date"]
        lines.append(_row("parse-failure rate", _pct(ingest["parse_failure_rate"]), cmd, date))
        lines.append(
            _row(
                "table-extraction rate",
                f"{_pct(ingest['table_extraction_rate'])} ({ingest['table_controls']}/{ingest['total_controls']})",
                cmd,
                date,
            )
        )
        lines.append(
            _row(
                "char-sanity pass",
                f"{_pct(ingest['char_sanity_pass_pct'])} ({ingest['char_sanity_passed']}/{ingest['char_sanity_total']})",
                cmd,
                date,
            )
        )
        lines.append(_row("chunks", str(ingest["total_chunks"]), cmd, date))
    else:
        lines.append("| _(no `results/ingest_*.json` yet)_ | | | |")
    lines.append("")

    lines += ["## Stages 1-3 — retrieval", "", "| Metric | Value | Command | Date |", "|---|---|---|---|"]
    if demo:
        cmd, date = demo["command"], demo["date"]
        d, h, r = demo["dense"], demo["hybrid"], demo["rerank"]
        lines.append(
            _row("recall@10 (dense)", f"{_pct(d['recall@10'])} (CI {_pct(d['recall@10_ci_lo'])}–{_pct(d['recall@10_ci_hi'])})", cmd, date)
        )
        lines.append(_row("recall@10 (hybrid)", _pct(h["recall@10"]), cmd, date))
        lines.append(_row("Δ recall@10 (hybrid − dense)", _pct(h["recall@10"] - d["recall@10"]), cmd, date))
        lines.append(_row("nDCG@5 (hybrid top-5)", _pct(demo["hybrid_ndcg5"]), cmd, date))
        lines.append(_row("nDCG@5 (hybrid+rerank)", _pct(r["ndcg@5"]), cmd, date))
        lines.append(_row("Δ nDCG@5 (rerank − none)", _pct(r["ndcg@5"] - demo["hybrid_ndcg5"]), cmd, date))
        lines.append(_row("p95 ms (dense / hybrid / rerank)", f"{d['p95_ms']:.0f} / {h['p95_ms']:.0f} / {r['p95_ms']:.0f}", cmd, date))
        lines.append(_row("test queries", str(demo["n_test_queries"]), cmd, date))
    else:
        lines.append("| _(no `results/demo_*.json` yet)_ | | | |")
    lines.append("")

    lines += ["### RRF weight sweep (k_leg=50)", "", "| dense× / bm25× | recall@10 |", "|---|---|"]
    if demo and demo.get("rrf_sweep"):
        for key, value in demo["rrf_sweep"].items():
            dense_w, bm25_w = key.split(",")
            lines.append(f"| {dense_w} / {bm25_w} | {_pct(value)} |")
    else:
        lines.append("| _(no sweep in artifact)_ | |")
    lines.append("")

    lines += ["## Stage 4 — ACL audit", "", "| Metric | Value | Command | Date |", "|---|---|---|---|"]
    if demo:
        cmd, date, a = demo["command"], demo["date"], demo["acl"]
        lines.append(_row("chunk checks", f"{a['n_checked']} across {a['n_combos']} combos", cmd, date))
        lines.append(_row("leaked chunks", str(a["n_leaked"]), cmd, date))
        lines.append(_row("prevented (of unauthorized)", f"{a['n_prevented']} ({_pct(a['prevented_rate'])})", cmd, date))
    else:
        lines.append("| _(no `results/demo_*.json` yet)_ | | | |")
    lines.append("")

    lines += ["## Stage 5 — eval gate", "", "| Metric | Value | Command | Date |", "|---|---|---|---|"]
    if ev:
        cmd, date = ev["command"], ev["date"]
        lines.append(_row("gate", "PASS" if ev["passed"] else "FAIL", cmd, date))
        for metric, value in ev["metrics"].items():
            lines.append(_row(f"{metric} (CI lower {ev['ci_lower'].get(metric, 0):.4f})", f"{value:.4f}", cmd, date))
        lines.append(_row("queries evaluated", str(ev["n_queries"]), cmd, date))
        lines.append(_row("failures / regressions / known", f"{ev['n_failures']} / {ev['n_regressions']} / {ev['n_known_failures']}", cmd, date))
    else:
        lines.append("| _(no `results/eval_*.json` yet)_ | | | |")
    lines.append("")

    lines += ["## Stage 6 — observability", "", "| Metric | Value | Command | Date |", "|---|---|---|---|"]
    if demo:
        cmd, date, o = demo["command"], demo["date"], demo["observability"]
        lines.append(_row("queries traced / retained", f"{o['n_queries']} / {o['n_retained']}", cmd, date))
        lines.append(_row("fully traced", _pct(o["pct_fully_traced"]), cmd, date))
    else:
        lines.append("| _(no `results/demo_*.json` yet)_ | | | |")
    lines.append("")

    lines += ["## Stage 7 — deploy", "", "| Metric | Value | Command | Date |", "|---|---|---|---|"]
    if load:
        cmd, date = load["command"], load["timestamp"]
        lines.append(_row("rps / duration", f"{load['rps']} / {load['duration_s']}s", cmd, date))
        lines.append(_row("status counts", str(load["status_codes"]), cmd, date))
        lines.append(_row("p50 / p95 / p99 ms", f"{load['p50_ms']} / {load['p95_ms']} / {load['p99_ms']}", cmd, date))
    else:
        lines.append("| _(no `results/load_*.json` yet — needs a redeploy)_ | | | |")
    lines.append("")

    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="write RESULTS.md")
    args = parser.parse_args()
    text = render()
    if args.write:
        Path("RESULTS.md").write_text(text)
        print("wrote RESULTS.md")
    else:
        print(text)


if __name__ == "__main__":
    main()
